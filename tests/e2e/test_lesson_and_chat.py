# Lesson flow (media, answers, retry, correction, result), chat with Léa, progress, mobile views.
# Usage: python3 test_lesson_and_chat.py <output dir>  (app served on http://localhost:4173)
import asyncio, sys, re
from playwright.async_api import async_playwright, expect
OUT=sys.argv[1]
results=[]
def check(name, ok, extra=''):
    results.append(('PASS' if ok else 'FAIL', name, extra))
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width':1440,'height':960})
        pg = await ctx.new_page()
        errors=[]
        pg.on('console', lambda m: errors.append(f'{m.type}: {m.text}') if m.type=='error' else None)
        pg.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
        await pg.goto('http://localhost:4173/', wait_until='networkidle'); await pg.wait_for_timeout(1200)
        txt = await pg.inner_text('main')
        check('dashboard shows 24 / 35', '24 / 35' in txt)
        check('dashboard shows 68%', '68%' in txt)
        await pg.get_by_role('button', name='Continuer la leçon').click(); await pg.wait_for_timeout(1500)
        check('lesson opened', 'Listen and answer' in await pg.inner_text('main'))
        await pg.screenshot(path=f'{OUT}/l_media.png')
        await pg.get_by_role('button', name=re.compile('aux questions')).click(); await pg.wait_for_timeout(600)
        await pg.get_by_role('radio', name=re.compile('A job interview')).click()
        await pg.screenshot(path=f'{OUT}/l_q1.png')
        await pg.get_by_role('button', name='Valider', exact=True).click(); await pg.wait_for_timeout(700)
        t = await pg.inner_text('main')
        check('wrong answer feedback + hint', 'Pas tout à fait' in t and 'Indice' in t)
        await pg.screenshot(path=f'{OUT}/l_q1_wrong.png')
        await pg.get_by_role('radio', name=re.compile('A travel plan')).click()
        await pg.get_by_role('button', name='Valider à nouveau').click(); await pg.wait_for_timeout(700)
        t = await pg.inner_text('main')
        check('second try correct', 'Bonne réponse, au deuxième essai' in t)
        await pg.get_by_role('button', name='Suivant', exact=True).click(); await pg.wait_for_timeout(500)
        await pg.get_by_role('radio', name='Vrai', exact=True).click()
        await pg.get_by_role('button', name='Valider', exact=True).click(); await pg.wait_for_timeout(600)
        check('tf correct', 'Bonne réponse !' in await pg.inner_text('main'))
        await pg.get_by_role('button', name='Suivant', exact=True).click(); await pg.wait_for_timeout(500)
        await pg.fill('input[id^="a-q3"]', 'They will book it tonight')
        await pg.get_by_role('button', name='Valider', exact=True).click(); await pg.wait_for_timeout(600)
        check('short answer accepted by keyword', 'Bonne réponse !' in await pg.inner_text('main'))
        await pg.get_by_role('button', name='Voir le résultat').click(); await pg.wait_for_timeout(1200)
        t = await pg.inner_text('main')
        check('result screen 2/3', '2 / 3 bonnes réponses' in t, t[:120])
        await pg.screenshot(path=f'{OUT}/l_result.png')
        await pg.get_by_role('button', name='Accueil', exact=True).click(); await pg.wait_for_timeout(900)
        t = await pg.inner_text('main')
        check('dashboard updated to 25 / 35', '25 / 35' in t)
        check('dashboard 71%', '71%' in t)
        await pg.get_by_role('button', name='Badges', exact=True).click(); await pg.wait_for_timeout(700)
        t = await pg.inner_text('main')
        check('badge Cap des 25 earned', bool(re.search(r'Cap des 25[\s\S]{0,120}Obtenu', t)))
        check('badge Oreille fine earned', bool(re.search(r'Oreille fine[\s\S]{0,120}Obtenu', t)))
        await pg.get_by_role('button', name='Messages', exact=True).click(); await pg.wait_for_timeout(600)
        await pg.fill('textarea', 'Où en suis-je ?'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(1800)
        t = await pg.inner_text('.chat-list')
        check('assistant answers progress question', '25 leçons sur 35' in t, t[-200:])
        await pg.screenshot(path=f'{OUT}/c_chat.png')
        await pg.fill('textarea', 'Prochaine leçon'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(1600)
        t = await pg.inner_text('.chat-list')
        check('recommends London landmarks', 'London landmarks' in t)
        await pg.get_by_role('button', name='Bibliothèque', exact=True).click(); await pg.wait_for_timeout(600)
        await pg.get_by_role('button', name=re.compile('^Toutes')).click()
        await pg.fill('#lib-q', 'python'); await pg.wait_for_timeout(300)
        n = await pg.locator('.course-grid .course-card').count()
        check('library search python -> 1', n == 1, str(n))
        await pg.fill('#lib-q', ''); await pg.get_by_role('button', name='Avancé', exact=True).click(); await pg.wait_for_timeout(300)
        n = await pg.locator('.course-grid .course-card').count()
        check('level filter avancé -> 2', n == 2, str(n))
        await pg.fill('#lib-q', 'zzzz'); await pg.wait_for_timeout(300)
        check('empty state', 'Aucun cours ne correspond' in await pg.inner_text('main'))
        await pg.reload(wait_until='networkidle'); await pg.wait_for_timeout(1000)
        await pg.goto('http://localhost:4173/'); await pg.wait_for_timeout(1200)
        check('progress persisted after reload', '25 / 35' in await pg.inner_text('main'))
        await pg.goto('http://localhost:4173/#progress'); await pg.wait_for_timeout(900)
        await pg.screenshot(path=f'{OUT}/d_progress2.png')
        # mobile lesson
        m = await b.new_context(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True)
        mp = await m.new_page()
        mp.on('pageerror', lambda e: errors.append(f'pageerror(m): {e}'))
        await mp.goto('http://localhost:4173/', wait_until='networkidle'); await mp.wait_for_timeout(1000)
        await mp.screenshot(path=f'{OUT}/m_home2.png')
        await mp.get_by_role('button', name='Continuer la leçon').click(); await mp.wait_for_timeout(1200)
        await mp.screenshot(path=f'{OUT}/m_lesson.png')
        sw = await mp.evaluate('document.documentElement.scrollWidth')
        check('mobile no horizontal overflow', sw <= 390, str(sw))
        for page in ['library','progress','messages','settings']:
            await mp.goto(f'http://localhost:4173/#{page}'); await mp.wait_for_timeout(700)
            sw = await mp.evaluate('document.documentElement.scrollWidth')
            check(f'mobile {page} no overflow', sw <= 390, str(sw))
        await mp.screenshot(path=f'{OUT}/m_settings.png')
        check('no console or page errors', not errors, str(errors[:3]))
        for r in results: print(*r)
        await b.close()
asyncio.run(main())
