# A full lesson (listen, answers, retry, correction, result), its effect on the home page and the
# badges, a conversation with Léa, the library filters and the search, saved progress, phone pages.
# Usage: python3 test_lesson_and_chat.py <output dir>  (app served on http://localhost:4173)
import asyncio, sys, re
from playwright.async_api import async_playwright
OUT = sys.argv[1]; results = []
def check(name, ok, extra=''): results.append(('PASS' if ok else 'FAIL', name, extra))
URL = 'http://localhost:4173/'

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1440, 'height': 960})
        pg = await ctx.new_page(); errors = []
        pg.on('console', lambda m: errors.append(f'{m.type}: {m.text}') if m.type == 'error' else None)
        pg.on('pageerror', lambda e: errors.append(f'pageerror: {e}'))
        await pg.goto(URL, wait_until='networkidle'); await pg.evaluate('localStorage.clear()'); await pg.reload(wait_until='networkidle'); await pg.wait_for_timeout(1200)
        txt = await pg.inner_text('main')
        check('home shows 24 lessons out of 35', '24 leçons sur 35 terminées' in txt and bool(re.search(r'\b24\s*sur 35', txt)))
        check('home shows 68 %', '68%' in txt.replace(' ', '').replace('\n', ''))
        await pg.get_by_role('button', name='Continuer la leçon').click(); await pg.wait_for_timeout(1500)
        check('lesson opens on its listening step', 'Listen and answer' in await pg.inner_text('main') and await pg.locator('.phase.is-current', has_text='Écouter').count() == 1)
        await pg.screenshot(path=f'{OUT}/l_media.png')
        await pg.get_by_role('button', name=re.compile('aux questions|Commencer les questions')).click(); await pg.wait_for_timeout(600)
        await pg.get_by_role('radio', name=re.compile('A job interview')).click()
        await pg.get_by_role('button', name='Valider', exact=True).click(); await pg.wait_for_timeout(700)
        t = await pg.inner_text('main')
        check('wrong answer: feedback with a hint', 'Pas tout à fait' in t and 'Indice' in t)
        await pg.screenshot(path=f'{OUT}/l_q1_wrong.png')
        await pg.get_by_role('radio', name=re.compile('A travel plan')).click()
        await pg.get_by_role('button', name='Valider à nouveau').click(); await pg.wait_for_timeout(700)
        check('second try correct', 'Bonne réponse, au deuxième essai' in await pg.inner_text('main'))
        await pg.get_by_role('button', name='Question suivante').click(); await pg.wait_for_timeout(500)
        await pg.get_by_role('radio', name='Vrai', exact=True).click()
        await pg.get_by_role('button', name='Valider', exact=True).click(); await pg.wait_for_timeout(600)
        check('true/false answer correct', 'Bonne réponse !' in await pg.inner_text('main'))
        await pg.get_by_role('button', name='Question suivante').click(); await pg.wait_for_timeout(500)
        await pg.fill('input[id^="a-q3"]', 'They will book it tonight')
        await pg.get_by_role('button', name='Valider', exact=True).click(); await pg.wait_for_timeout(600)
        check('short answer accepted by keyword', 'Bonne réponse !' in await pg.inner_text('main'))
        await pg.get_by_role('button', name='Voir le résultat').click(); await pg.wait_for_timeout(1200)
        t = await pg.inner_text('main')
        check('result: 2 / 3 right the first time', '2 / 3 bonnes réponses du premier coup' in t, t[:160])
        check('result: every step done', await pg.locator('.phase.is-done').count() == 4)
        check('result: next lesson offered', await pg.get_by_role('button', name='Leçon suivante').count() == 1)
        await pg.screenshot(path=f'{OUT}/l_result.png')
        await pg.locator('.side').get_by_role('button', name='Accueil', exact=True).click(); await pg.wait_for_timeout(900)
        t = await pg.inner_text('main')
        check('home updated to 25 out of 35', '25 leçons sur 35 terminées' in t)
        check('home updated to 71 %', '71%' in t.replace(' ', '').replace('\n', ''))
        await pg.locator('.side').get_by_role('button', name='Badges', exact=True).click(); await pg.wait_for_timeout(800)
        t = await pg.inner_text('main')
        check('badge « Cap des 25 » earned today', bool(re.search(r'Cap des 25[\s\S]{0,160}Gagné aujourd’hui', t)))
        check('badge « Oreille fine » earned today', bool(re.search(r'Oreille fine[\s\S]{0,160}Gagné aujourd’hui', t)))
        await pg.goto(URL + '#messages'); await pg.wait_for_timeout(800)
        await pg.fill('#chat-text', 'Où en suis-je ?'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(1800)
        t = await pg.inner_text('.chat-list')
        check('Léa answers a progress question', '25 leçons sur 35' in t, t[-200:])
        check('her answer carries the course card', await pg.locator('.msg-lea .msg-card.mc-course').count() >= 2)
        await pg.screenshot(path=f'{OUT}/c_chat.png')
        await pg.fill('#chat-text', 'Prochaine leçon'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(1600)
        check('she recommends « London landmarks »', 'London landmarks' in await pg.inner_text('.chat-list'))
        n_msgs = await pg.locator('.chat-list .msg').count()
        await pg.get_by_role('button', name='Nouvelle discussion').click(); await pg.wait_for_timeout(500)
        check('new conversation, the previous one in the history', await pg.locator('.chat-list .msg').count() == 1 and n_msgs > 3)
        await pg.get_by_role('button', name='Historique').click(); await pg.wait_for_timeout(300)
        check('history lists the archived conversation', await pg.locator('.history-pop [role="menuitem"]').count() == 4)
        await pg.keyboard.press('Escape')
        # library: level and category filters, global search
        await pg.goto(URL + '#library'); await pg.wait_for_timeout(800)
        total = await pg.locator('.course-grid .course-card').count()
        await pg.get_by_role('group', name='Niveau').get_by_role('button', name='Avancé', exact=True).click(); await pg.wait_for_timeout(300)
        adv = await pg.locator('.course-grid .course-card').count()
        levels = await pg.locator('.course-grid .course-card .lvl').all_inner_texts()
        check('level filter: only advanced courses', 0 < adv < total and all('Avancé' in x for x in levels), f'{adv}/{total} {levels}')
        await pg.get_by_role('group', name='Niveau').get_by_role('button', name='Tous niveaux').click()
        await pg.locator('.cat-chips').get_by_role('button', name=re.compile('^Informatique')).click(); await pg.wait_for_timeout(300)
        info = await pg.locator('.course-grid .course-card').count()
        check('category filter: Informatique', info == 2, str(info))
        await pg.fill('#global-search', 'python'); await pg.wait_for_timeout(300)
        res = await pg.inner_text('#search-results')
        check('search finds the Python course', 'Python : premiers pas' in res, res[:80])
        await pg.keyboard.press('Enter'); await pg.wait_for_timeout(900)
        check('Enter opens the first result', 'Python : premiers pas' in await pg.inner_text('.cd-hero'))
        await pg.reload(wait_until='networkidle'); await pg.wait_for_timeout(1000)
        await pg.goto(URL); await pg.wait_for_timeout(1200)
        check('progress kept after reload', '25 leçons sur 35 terminées' in await pg.inner_text('main'))
        # phone
        m = await b.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
        mp = await m.new_page()
        mp.on('pageerror', lambda e: errors.append(f'pageerror(m): {e}'))
        await mp.goto(URL, wait_until='networkidle'); await mp.wait_for_timeout(1000)
        await mp.screenshot(path=f'{OUT}/m_home.png')
        await mp.get_by_role('button', name='Continuer la leçon').click(); await mp.wait_for_timeout(1200)
        sticky = await mp.evaluate("(() => { const n = document.querySelector('.lm-sticky'); if (!n) return null; const r = n.getBoundingClientRect(); return [Math.round(r.bottom), innerHeight]; })()")
        check('phone lesson: the main button stays at the bottom of the screen', sticky and sticky[1] - 40 < sticky[0] <= sticky[1], str(sticky))
        await mp.get_by_role('button', name=re.compile('aux questions|Commencer les questions')).click(); await mp.wait_for_timeout(600)
        await mp.get_by_role('radio', name=re.compile('A job interview')).click()
        await mp.get_by_role('button', name='Valider', exact=True).click(); await mp.wait_for_timeout(1300)
        sheet = await mp.evaluate("(() => { const n = document.querySelector('.lm-sheet.has-feedback'); if (!n) return null; const r = n.getBoundingClientRect(); return [Math.round(r.bottom), innerHeight, !!n.querySelector('.fb-lea .lea'), n.innerText.slice(0, 40)]; })()")
        check('phone lesson: feedback sheet at the bottom with Léa’s face', sheet and abs(sheet[0] - sheet[1]) <= 1 and sheet[2] and 'Pas tout à fait' in sheet[3], str(sheet))
        await mp.screenshot(path=f'{OUT}/m_lesson.png')
        for page in ['library', 'progress', 'messages', 'settings', 'badges', 'subscription']:
            await mp.goto(f'{URL}#{page}'); await mp.wait_for_timeout(700)
            sw = await mp.evaluate('document.documentElement.scrollWidth')
            check(f'phone {page}: no horizontal overflow', sw <= 390, str(sw))
        check('no console or page errors', not errors, str(errors[:3]))
        for r in results: print(*r)
        await b.close()
asyncio.run(main())
